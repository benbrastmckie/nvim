#!/usr/bin/env bash
# roadmap-preflight-lib.sh - Single source of truth for classifying specs/ROADMAP.md (the
# generated sentinel, CLASSIC_HEADERS, the fenced-/orchestrate-block predicate, detect_layout),
# plus the preflight gate that sits strictly IN FRONT of roadmap-integration.sh's write modes: a
# five-way classify entry point (absent/generated/classic/stage/unknown) and a scaffolder for
# the one verdict where creating the file is a purely mechanical act.
#
# Modeled on scripts/lib/status-vocabulary.sh's "one sourced shared library, many consumers"
# shape. roadmap-integration.sh sources this file and keeps zero copies of its own; consumers
# are found live via `grep -rl 'roadmap-preflight-lib.sh' agent-system/extensions`.
#
# WHY classification lives here and not in roadmap-integration.sh: that script parses $@ and
# calls `exit` at top level with no `BASH_SOURCE` run-as-script guard, so sourcing it directly
# (to reuse detect_layout) would run its argument parser against the sourcing shell's own $@ and
# could exit that shell. Everything here is side-effect-free when sourced; the run-as-script
# guard at the bottom lets a Bash-only caller invoke it safely without sourcing.
#
# THE VERDICTS
#   generated  first line is the sentinel: owned by the generator, safe to overwrite
#   absent     no file
#   classic    a hand-authored file with the eight classic headers
#   stage      a hand-authored file in the stage layout
#   unknown    any other file
# classic, stage and unknown all mean "hand-authored content the generator cannot reproduce".
# They are told apart only so scripts/migrate-roadmap-to-milestones.sh knows how to read the
# file it is migrating; no caller renders any of the three.
#
# WHAT THIS FILE NEVER DOES: it never weakens, bypasses, or adds a --force path to
# roadmap-integration.sh's Destructive-Overwrite Refusal (context/formats/roadmap-format.md).
# roadmap_preflight_scaffold below writes ONLY the sentinel line, ONLY onto an absent path, and
# refuses outright on any existing file.
#
# Usage (sourced, e.g. from another script):
#   source "${SCRIPT_DIR}/lib/roadmap-preflight-lib.sh"
#   verdict="$(roadmap_preflight_classify "$ROADMAP_PATH")"
#   roadmap_preflight_scaffold "$ROADMAP_PATH"                # only correct on absent
#
# Usage (run as a script, for a Bash-only caller that must not source arbitrary library code):
#   bash scripts/lib/roadmap-preflight-lib.sh classify specs/ROADMAP.md
#   bash scripts/lib/roadmap-preflight-lib.sh scaffold specs/ROADMAP.md

# ─── Layout-classification vocabulary ───────────────────────────────────────────────────────

# ROADMAP_GENERATED_SENTINEL -- the fixed first line of a file roadmap-integration.sh renders
# wholly from state. A file whose first line is exactly this string classifies as `generated`:
# every byte below it is owned by the generator and is safe to overwrite. Classification by this
# one line replaces any reading of section headers for such a file.
# shellcheck disable=SC2034  # read by the scripts that source this library
ROADMAP_GENERATED_SENTINEL='<!-- generated by roadmap-integration.sh from specs/state.json; do not edit -->'

# CLASSIC_HEADERS -- the eight literal headers of a hand-authored classic file, in order. Kept
# only to classify an unmigrated file; nothing renders these headers.
CLASSIC_HEADERS=(
  "## Goal"
  "## Gate state"
  "## Next"
  "## Open work"
  "## Checks before and after every call"
  "## Settled decisions (do not re-litigate)"
  "## Standing rules"
  "## Unfiled observations (none worth a task yet)"
)

# body_has_orchestrate_fence BODY -> status 0 iff some fenced code block (a line that is exactly
# ``` optionally followed by a language tag, e.g. ```bash) within BODY contains at least one line
# matching ^/orchestrate ; status 1 otherwise. Used by roadmap_has_orchestrate_fence (whole
# file, for detect_layout).
body_has_orchestrate_fence() {
  local body="$1"
  awk '
    /^```/ { in_fence = !in_fence; next }
    in_fence && /^\/orchestrate / { found = 1 }
    END { exit (found ? 0 : 1) }
  ' <<<"$body"
}

# roadmap_has_orchestrate_fence FILE -> body_has_orchestrate_fence applied to the whole file's
# content. Helper for detect_layout's stage predicate (checked before any section splitting).
roadmap_has_orchestrate_fence() {
  body_has_orchestrate_fence "$(cat "$1")"
}

# detect_layout FILE -> "generated" | "classic" | "stage" | "unknown"
#
#   generated: the file's first line is exactly ROADMAP_GENERATED_SENTINEL. Tested first, so
#            a generated file is never classified by whatever headers its body happens to hold.
#   classic: every literal header in CLASSIC_HEADERS is present (exact match).
#   stage:   a header matching ^## Stage [0-9]+ exists, AND some fenced code block holds an
#            /orchestrate line -- structural, so it survives a cosmetic rename of the stage
#            headers' own text.
#   unknown: none of the above.
detect_layout() {
  local file="$1" h is_classic=1 first_line=""
  IFS= read -r first_line <"$file" || true
  if [[ "$first_line" == "$ROADMAP_GENERATED_SENTINEL" ]]; then
    echo "generated"
    return 0
  fi

  for h in "${CLASSIC_HEADERS[@]}"; do
    grep -qxF "$h" "$file" || { is_classic=0; break; }
  done
  if [[ "$is_classic" -eq 1 ]]; then
    echo "classic"
    return 0
  fi

  if grep -qE '^## Stage [0-9]+' "$file" && roadmap_has_orchestrate_fence "$file"; then
    echo "stage"
    return 0
  fi

  echo "unknown"
}

# ─── Preflight classify (new) ──────────────────────────────────────────────────────────────

# roadmap_preflight_classify PATH -> "absent" | "generated" | "classic" | "stage" | "unknown";
# always exits 0 (classification never fails). "absent" is checked here, before detect_layout is
# reached, so no caller has to re-derive file existence on its own.
roadmap_preflight_classify() {
  local path="$1"
  if [[ ! -f "$path" ]]; then
    echo "absent"
    return 0
  fi
  detect_layout "$path"
  return 0
}

# roadmap_preflight_scaffold PATH -> creates PATH holding only the generated sentinel line, so
# the file classifies `generated` and the next --regenerate fills it from state. Correct ONLY
# for the `absent` verdict. Refuses (non-zero, named stderr reason, no write) on any existing
# file: a generated file needs no scaffold, and a hand-authored one (classic, stage, unknown)
# holds content that scripts/migrate-roadmap-to-milestones.sh must move first.
roadmap_preflight_scaffold() {
  local path="$1" verdict
  verdict="$(roadmap_preflight_classify "$path")"

  case "$verdict" in
    absent) ;;
    generated)
      echo "ERROR: roadmap_preflight_scaffold refuses to write ${path}: it already classifies as" >&2
      echo "       'generated'; run roadmap-integration.sh --regenerate instead." >&2
      return 1
      ;;
    *)
      echo "ERROR: roadmap_preflight_scaffold refuses to write ${path}: it classifies as" >&2
      echo "       '${verdict}', a hand-authored file. Run migrate-roadmap-to-milestones.sh" >&2
      echo "       (--dry-run first) to move its content into state and a retained-prose file." >&2
      return 1
      ;;
  esac

  mkdir -p "$(dirname "$path")"
  printf '%s\n' "$ROADMAP_GENERATED_SENTINEL" > "$path"
}

# ─── Run-as-script CLI guard ────────────────────────────────────────────────────────────────
#
# Argument parsing stays strictly inside this guard so sourcing this file from a shell with
# arbitrary $@ set neither parses arguments nor exits -- the exact hazard that makes sourcing
# roadmap-integration.sh directly unsafe (see the file header above).
if [[ "${BASH_SOURCE[0]}" == "${0}" ]]; then
  set -euo pipefail
  roadmap_preflight_usage() {
    echo "Usage: $(basename "${BASH_SOURCE[0]}") classify PATH" >&2
    echo "       $(basename "${BASH_SOURCE[0]}") scaffold PATH" >&2
  }

  if [[ $# -ne 2 ]]; then
    roadmap_preflight_usage
    exit 1
  fi

  case "$1" in
    classify)
      roadmap_preflight_classify "$2"
      ;;
    scaffold)
      roadmap_preflight_scaffold "$2"
      ;;
    *)
      echo "ERROR: unknown subcommand: $1" >&2
      roadmap_preflight_usage
      exit 1
      ;;
  esac
fi
