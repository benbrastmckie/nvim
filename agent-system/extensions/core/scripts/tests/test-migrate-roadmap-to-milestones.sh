#!/usr/bin/env bash
# test-migrate-roadmap-to-milestones.sh - Regression suite for migrate-roadmap-to-milestones.sh,
# the one-time migration from the flat roadmap shape to the milestone shape.
#
# ISOLATION CONTRACT: every case builds a fresh scratch project root under mktemp -d with its
# own <scratch>/.claude/scripts/ tree and <scratch>/specs/{state.json,ROADMAP.md}, and drives the
# migration exclusively via --roadmap/--state/--retained pointed at the scratch tree. The suite
# never reads or writes the real specs/ tree.
#
# Fixture entities are referred to as "item N" throughout, never by any other noun: these are
# synthetic rows, unrelated to this repository's own numbering.
#
# Exit codes: 0 -- all cases PASS; 1 -- at least one case FAILED; 2 -- environment error.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/../lib/common.sh"
REPO_ROOT="$(common_test_repo_root "$SCRIPT_DIR")"

MIGRATE_SRC="$(common_test_resolve_subject "migrate-roadmap-to-milestones.sh" "source-store" \
  "$REPO_ROOT/.claude/scripts/migrate-roadmap-to-milestones.sh" \
  "$SCRIPT_DIR/../migrate-roadmap-to-milestones.sh")" || exit 2
common_test_declare_subject "$MIGRATE_SRC"

DEP_SCRIPTS=(state-write.sh task-lock.sh roadmap-integration.sh generate-task-order.sh deploy-root-guard.sh validate-state.sh)
DEP_LIBS=(common.sh status-vocabulary.sh project-number-inuse.sh task-lookup-lib.sh roadmap-preflight-lib.sh roadmap-entries-lib.sh)

for d in "${DEP_SCRIPTS[@]}"; do
  if [[ ! -f "$SCRIPT_DIR/../$d" ]]; then
    echo "ERROR: dependency script not found at $SCRIPT_DIR/../$d" >&2
    exit 2
  fi
done
for d in "${DEP_LIBS[@]}"; do
  if [[ ! -f "$SCRIPT_DIR/../lib/$d" ]]; then
    echo "ERROR: dependency lib not found at $SCRIPT_DIR/../lib/$d" >&2
    exit 2
  fi
done

if ! command -v jq >/dev/null 2>&1; then
  echo "ERROR: jq is required and is not on PATH" >&2
  exit 2
fi

PASSED=0
FAILED=0

TOP_WORKDIR="$(mktemp -d)"
cleanup() { [[ -n "${TOP_WORKDIR:-}" && -d "$TOP_WORKDIR" ]] && rm -rf "$TOP_WORKDIR"; }
trap cleanup EXIT

SENTINEL='<!-- generated by roadmap-integration.sh from specs/state.json; do not edit -->'

build_scratch() {
  local scratch
  scratch="$(mktemp -d -p "$TOP_WORKDIR")"
  mkdir -p "$scratch/.claude/scripts/lib" "$scratch/specs"
  cp "$MIGRATE_SRC" "$scratch/.claude/scripts/migrate-roadmap-to-milestones.sh"
  local d
  for d in "${DEP_SCRIPTS[@]}"; do
    cp "$SCRIPT_DIR/../$d" "$scratch/.claude/scripts/$d"
  done
  for d in "${DEP_LIBS[@]}"; do
    cp "$SCRIPT_DIR/../lib/$d" "$scratch/.claude/scripts/lib/$d"
  done
  chmod +x "$scratch/.claude/scripts/"*.sh
  echo "$scratch"
}

run_migrate() {
  local scratch="$1"; shift
  "$scratch/.claude/scripts/migrate-roadmap-to-milestones.sh" \
    --roadmap "$scratch/specs/ROADMAP.md" --state "$scratch/specs/state.json" \
    --retained "$scratch/specs/archive/retained.md" "$@"
}

# A flat-shape store: two batches (one with rationale and flags) and two notes arrays.
write_state_fixture() {
  local scratch="$1"
  cat > "$scratch/specs/state.json" <<'EOF'
{
  "next_project_number": 4,
  "active_topics": ["alpha"],
  "active_projects": [
    {"project_number": 1, "project_name": "item_one", "status": "not_started", "title": "Item one description", "topic": "alpha", "dependencies": []},
    {"project_number": 2, "project_name": "item_two", "status": "not_started", "title": "Item two description", "topic": "alpha", "dependencies": []},
    {"project_number": 3, "project_name": "item_three", "status": "not_started", "title": "Item three description", "topic": "alpha", "dependencies": []}
  ],
  "roadmap_batches": [
    {"task_ids": [1, 2], "description": "batch one", "rationale": "Batch one rationale.\nSecond rationale line.", "flags": "--hard"},
    {"task_ids": [3], "description": "batch two"}
  ],
  "roadmap_notes": {
    "next_preamble": ["Notes preamble paragraph one.", "Notes preamble paragraph two,\nwrapped onto a second line."],
    "next_postamble": ["Notes postamble paragraph."],
    "open_work_trailer": []
  }
}
EOF
}

# A classic eight-header file. The over-bound settled decision is 330 characters of body.
write_roadmap_fixture() {
  local scratch="$1"
  local long_item
  long_item="$(printf 'x%.0s' $(seq 1 330))"
  cat > "$scratch/specs/ROADMAP.md" <<EOF
# Roadmap

*Fixture preamble, kept verbatim.*

## Goal

Fixture goal paragraph one,
hard-wrapped onto a second line.

Fixture goal paragraph two.

## Gate state

Fixture gate measurement, dated.

## Next

Notes preamble paragraph one.

\`\`\`
/orchestrate 1, 2 --hard   # batch one
/orchestrate 3   # batch two
\`\`\`

## Open work

**Alpha (3)**
\`\`\`
1 ready               Item one description
\`\`\`

## Checks before and after every call

An introductory sentence that is not a list item.

- Check one is a single line.
- Check two is hard-wrapped
  across two physical lines.

## Settled decisions (do not re-litigate)

1. Decision one fits the bound.
2. ${long_item}

## Standing rules

- Rule one.
- Rule two.

## Unfiled observations (none worth a task yet)

Fixture observation, kept verbatim.
EOF
}

write_stage_roadmap_fixture() {
  local scratch="$1"
  cat > "$scratch/specs/ROADMAP.md" <<'EOF'
# Roadmap

Stage fixture preamble.

## Run order at a glance

```
/orchestrate 1, 2 --hard   # batch one
/orchestrate 3   # batch two
```

## Stage 1 -- first things

- Stage one bullet, authored.

## Stage 2 -- later things

Stage two prose, authored.
EOF
}

sum_of() { sha256sum "$1" | awk '{print $1}'; }

# ─── Case 1: classic happy path ───────────────────────────────────────────────────────────────
scratch1="$(build_scratch)"
write_state_fixture "$scratch1"
write_roadmap_fixture "$scratch1"
jq -S -c '.roadmap_batches' "$scratch1/specs/state.json" > "$scratch1/batches-before.json"

out1="$(run_migrate "$scratch1" --session-id sess_test_1 2>"$scratch1/stderr.txt")"
rc1=$?
if [[ "$rc1" -eq 0 ]] && grep -qF "Losslessness accounting PASSED" <<<"$out1"; then
  common_test_pass "classic: real run exits 0 and reports the accounting passed"
else
  common_test_fail "classic: expected exit 0 with the accounting-passed line (rc=$rc1; $(cat "$scratch1/stderr.txt"))"
  common_test_info "$out1"
fi

if jq -e '(.roadmap_milestones | length) == 1
          and .roadmap_milestones[0].id == "M1"
          and .roadmap_milestones[0].title == "Current work"
          and .roadmap_milestones[0].progress.status == "active"
          and .roadmap_milestones[0].review.state == "none"
          and (.roadmap_milestones[0].aim | length) > 0' "$scratch1/specs/state.json" >/dev/null 2>&1; then
  common_test_pass "classic: one neutral milestone M1 (active, review none) holds the work"
else
  common_test_fail "classic: unexpected roadmap_milestones: $(jq -c '.roadmap_milestones' "$scratch1/specs/state.json" 2>&1)"
fi

jq -S -c '.roadmap_milestones[0].batches' "$scratch1/specs/state.json" > "$scratch1/batches-after.json" 2>/dev/null
if cmp -s "$scratch1/batches-before.json" "$scratch1/batches-after.json"; then
  common_test_pass "classic: every flat batch is nested in order and unchanged (task_ids, description, rationale, flags)"
else
  common_test_fail "classic: nested batches differ from the flat ones"
fi

if jq -e '(has("roadmap_batches") or has("roadmap_notes")) | not' "$scratch1/specs/state.json" >/dev/null 2>&1; then
  common_test_pass "classic: the flat roadmap_batches and roadmap_notes keys are deleted"
else
  common_test_fail "classic: a flat roadmap key survived the migration"
fi

if jq -e '.primary_goals == ["Fixture goal paragraph one, hard-wrapped onto a second line.", "Fixture goal paragraph two."]' \
    "$scratch1/specs/state.json" >/dev/null 2>&1; then
  common_test_pass "classic: ## Goal paragraphs become primary_goals, hard wraps joined"
else
  common_test_fail "classic: unexpected primary_goals: $(jq -c '.primary_goals' "$scratch1/specs/state.json" 2>&1)"
fi

if jq -e '.roadmap_context.rules == ["Rule one.", "Rule two."]
          and .roadmap_context.conventions == ["Check one is a single line.", "Check two is hard-wrapped across two physical lines.", "Decision one fits the bound."]' \
    "$scratch1/specs/state.json" >/dev/null 2>&1; then
  common_test_pass "classic: rules and conventions hold the list items, markers stripped, multi-line items joined"
else
  common_test_fail "classic: unexpected roadmap_context: $(jq -c '.roadmap_context' "$scratch1/specs/state.json" 2>&1)"
fi

ret1="$scratch1/specs/archive/retained.md"
if [[ -f "$ret1" ]] \
    && grep -qxF '## (preamble)' "$ret1" && grep -qxF '*Fixture preamble, kept verbatim.*' "$ret1" \
    && grep -qxF '## Gate state' "$ret1" && grep -qxF 'Fixture gate measurement, dated.' "$ret1" \
    && grep -qxF '## Unfiled observations (none worth a task yet)' "$ret1" \
    && grep -qxF 'Fixture observation, kept verbatim.' "$ret1" \
    && grep -qxF 'An introductory sentence that is not a list item.' "$ret1"; then
  common_test_pass "classic: preamble, Gate state, Unfiled observations and non-item prose are retained verbatim under their headers"
else
  common_test_fail "classic: retained-prose file is missing expected content"
  common_test_info "$(cat "$ret1" 2>&1)"
fi

if grep -qxF '## roadmap_notes.next_preamble' "$ret1" && grep -qxF 'wrapped onto a second line.' "$ret1" \
    && grep -qxF '## roadmap_notes.next_postamble' "$ret1" && grep -qxF 'Notes postamble paragraph.' "$ret1"; then
  common_test_pass "classic: every roadmap_notes string is retained under its own key"
else
  common_test_fail "classic: roadmap_notes strings missing from the retained-prose file"
fi

# ─── Case 2: an over-bound item is retained whole, never truncated ────────────────────────────
long_line="2. $(printf 'x%.0s' $(seq 1 330))"
if grep -qxF "$long_line" "$ret1" && grep -q '^WARN: over-bound item retained whole (330 > 300 characters' "$scratch1/stderr.txt" \
    && ! jq -e '.roadmap_context.conventions | map(length > 300) | any' "$scratch1/specs/state.json" >/dev/null 2>&1; then
  common_test_pass "over-bound: the item is retained whole with one WARN and no state field exceeds its bound"
else
  common_test_fail "over-bound: expected the 330-character item verbatim in the retained file plus a WARN ($(cat "$scratch1/stderr.txt"))"
fi

if [[ "$(sed -n '1p' "$scratch1/specs/ROADMAP.md")" == "$SENTINEL" ]] \
    && grep -qxF -- '- Fixture goal paragraph two.' "$scratch1/specs/ROADMAP.md" \
    && grep -qxF '## M1: Current work' "$scratch1/specs/ROADMAP.md" \
    && grep -qxF '/orchestrate 1, 2 --hard' "$scratch1/specs/ROADMAP.md" \
    && ! grep -qF 'Fixture gate measurement' "$scratch1/specs/ROADMAP.md"; then
  common_test_pass "classic: the roadmap file is rewritten as a generated file from the migrated state"
else
  common_test_fail "classic: the roadmap file was not rewritten as a generated file"
  common_test_info "$(head -20 "$scratch1/specs/ROADMAP.md")"
fi

vs_out="$(bash "$scratch1/.claude/scripts/validate-state.sh" "$scratch1/specs/state.json" 2>&1)"
if ! grep -qF 'flat roadmap key' <<<"$vs_out" && ! grep -qE 'Check 13.*(FAIL|WARN)' <<<"$vs_out"; then
  common_test_pass "classic: validate-state.sh reports no flat-key warning and no Check 13 finding on the migrated store"
else
  common_test_fail "classic: validate-state.sh still reports a roadmap finding"
  common_test_info "$(grep -F 'Check 13' <<<"$vs_out")"
fi

# ─── Case 3: idempotent refusal, then --force ─────────────────────────────────────────────────
sum_state_before="$(sum_of "$scratch1/specs/state.json")"
run_migrate "$scratch1" --session-id sess_test_1 >/dev/null 2>"$scratch1/stderr-again.txt"
rc_again=$?
if [[ "$rc_again" -eq 2 ]] && grep -qF 'already migrated' "$scratch1/stderr-again.txt" \
    && [[ "$(sum_of "$scratch1/specs/state.json")" == "$sum_state_before" ]]; then
  common_test_pass "idempotence: a second run refuses with exit 2 and leaves state untouched"
else
  common_test_fail "idempotence: expected exit 2 and an unchanged state (rc=$rc_again)"
fi

jq -S -c '.roadmap_milestones' "$scratch1/specs/state.json" > "$scratch1/ms-before-force.json"
run_migrate "$scratch1" --force --session-id sess_test_1 >/dev/null 2>"$scratch1/stderr-force.txt"
rc_force=$?
jq -S -c '.roadmap_milestones' "$scratch1/specs/state.json" > "$scratch1/ms-after-force.json"
if [[ "$rc_force" -eq 0 ]] && cmp -s "$scratch1/ms-before-force.json" "$scratch1/ms-after-force.json" \
    && [[ "$(sed -n '1p' "$scratch1/specs/ROADMAP.md")" == "$SENTINEL" ]]; then
  common_test_pass "--force: runs on a migrated store and keeps its milestones when no flat batch is left"
else
  common_test_fail "--force: expected exit 0 with milestones unchanged (rc=$rc_force; $(cat "$scratch1/stderr-force.txt"))"
fi

# ─── Case 4: --dry-run writes nothing ─────────────────────────────────────────────────────────
scratch4="$(build_scratch)"
write_state_fixture "$scratch4"
write_roadmap_fixture "$scratch4"
sum_s="$(sum_of "$scratch4/specs/state.json")"
sum_r="$(sum_of "$scratch4/specs/ROADMAP.md")"
out4="$(run_migrate "$scratch4" --dry-run 2>/dev/null)"
rc4=$?
if [[ "$rc4" -eq 0 ]] && grep -qF "Losslessness accounting PASSED" <<<"$out4" \
    && grep -qF 'Batches: 2 flat -> 2 under milestone M1' <<<"$out4" \
    && grep -qF 'primary_goals +2, roadmap_context.rules +2, roadmap_context.conventions +3' <<<"$out4" \
    && [[ "$(sum_of "$scratch4/specs/state.json")" == "$sum_s" ]] \
    && [[ "$(sum_of "$scratch4/specs/ROADMAP.md")" == "$sum_r" ]] \
    && [[ ! -e "$scratch4/specs/archive/retained.md" ]]; then
  common_test_pass "--dry-run: prints the accounting and writes neither state, the roadmap nor the retained file"
else
  common_test_fail "--dry-run: expected the accounting and no write (rc=$rc4)"
  common_test_info "$out4"
fi

# ─── Case 5: the gate fails on an unaccounted line and nothing is written ─────────────────────
# A roadmap_notes string holding a line shaped like a section header cannot be read back out of
# the retained file under its own key, so its lines are unaccounted and the gate must stop.
scratch5="$(build_scratch)"
write_state_fixture "$scratch5"
write_roadmap_fixture "$scratch5"
jq '.roadmap_notes.next_postamble += ["## Header-shaped line\nfollowed by a body line"]' \
  "$scratch5/specs/state.json" > "$scratch5/specs/state.json.new" \
  && mv "$scratch5/specs/state.json.new" "$scratch5/specs/state.json"
cp "$scratch5/specs/state.json" "$scratch5/state-before.json"
cp "$scratch5/specs/ROADMAP.md" "$scratch5/roadmap-before.md"
run_migrate "$scratch5" --session-id sess_test_5 >/dev/null 2>"$scratch5/stderr.txt"
rc5=$?
if [[ "$rc5" -eq 1 ]] && grep -qF 'losslessness accounting FAILED' "$scratch5/stderr.txt" \
    && grep -qF 'roadmap_notes line not retained: ## Header-shaped line' "$scratch5/stderr.txt" \
    && cmp -s "$scratch5/state-before.json" "$scratch5/specs/state.json" \
    && cmp -s "$scratch5/roadmap-before.md" "$scratch5/specs/ROADMAP.md" \
    && [[ ! -e "$scratch5/specs/archive/retained.md" ]]; then
  common_test_pass "gate: an unaccounted line is named, the exit is non-zero, and state, roadmap and retained file are untouched"
else
  common_test_fail "gate: expected exit 1 with the line named and nothing written (rc=$rc5; $(cat "$scratch5/stderr.txt"))"
fi

# ─── Case 6: stage layout ─────────────────────────────────────────────────────────────────────
scratch6="$(build_scratch)"
write_state_fixture "$scratch6"
write_stage_roadmap_fixture "$scratch6"
out6="$(run_migrate "$scratch6" --session-id sess_test_6 2>"$scratch6/stderr.txt")"
rc6=$?
ret6="$scratch6/specs/archive/retained.md"
if [[ "$rc6" -eq 0 ]] && grep -qF 'Layout of' <<<"$out6" && grep -qF ': stage' <<<"$out6" \
    && grep -qxF '## Stage 1 -- first things' "$ret6" && grep -qxF -- '- Stage one bullet, authored.' "$ret6" \
    && grep -qxF '## Stage 2 -- later things' "$ret6" && grep -qxF 'Stage two prose, authored.' "$ret6" \
    && grep -qxF 'Stage fixture preamble.' "$ret6" \
    && ! grep -qF 'Run order at a glance' "$ret6" \
    && jq -e '(.roadmap_milestones[0].batches | length) == 2 and (has("primary_goals") | not)' "$scratch6/specs/state.json" >/dev/null 2>&1 \
    && [[ "$(sed -n '1p' "$scratch6/specs/ROADMAP.md")" == "$SENTINEL" ]]; then
  common_test_pass "stage layout: every section but the run-order one is retained; batches nest; the file becomes generated"
else
  common_test_fail "stage layout: unexpected result (rc=$rc6; $(cat "$scratch6/stderr.txt"))"
  common_test_info "$(cat "$ret6" 2>&1)"
fi

# ─── Case 7: prerequisite detection ───────────────────────────────────────────────────────────
scratch7="$(build_scratch)"
write_state_fixture "$scratch7"
write_roadmap_fixture "$scratch7"
jq 'del(.roadmap_batches, .roadmap_notes)' "$scratch7/specs/state.json" > "$scratch7/specs/state.json.new" \
  && mv "$scratch7/specs/state.json.new" "$scratch7/specs/state.json"
cp "$scratch7/specs/state.json" "$scratch7/state-before.json"
run_migrate "$scratch7" --session-id sess_test_7 >/dev/null 2>"$scratch7/stderr.txt"
rc7=$?
if [[ "$rc7" -eq 3 ]] && grep -qF 'migrate-roadmap-next-to-state.sh' "$scratch7/stderr.txt" \
    && cmp -s "$scratch7/state-before.json" "$scratch7/specs/state.json" \
    && [[ "$(sed -n '1p' "$scratch7/specs/ROADMAP.md")" == "# Roadmap" ]]; then
  common_test_pass "prerequisite: a hand-authored ## Next with no batches in state stops with exit 3 and names the earlier migration"
else
  common_test_fail "prerequisite: expected exit 3 naming migrate-roadmap-next-to-state.sh (rc=$rc7; $(cat "$scratch7/stderr.txt"))"
fi

# ─── Case 8: an existing retained-prose target is never overwritten ───────────────────────────
scratch8="$(build_scratch)"
write_state_fixture "$scratch8"
write_roadmap_fixture "$scratch8"
mkdir -p "$scratch8/specs/archive"
echo "earlier retained prose" > "$scratch8/specs/archive/retained.md"
cp "$scratch8/specs/state.json" "$scratch8/state-before.json"
run_migrate "$scratch8" --session-id sess_test_8 >/dev/null 2>"$scratch8/stderr.txt"
rc8=$?
if [[ "$rc8" -eq 2 ]] && [[ "$(cat "$scratch8/specs/archive/retained.md")" == "earlier retained prose" ]] \
    && cmp -s "$scratch8/state-before.json" "$scratch8/specs/state.json" \
    && grep -qF -- '--retained' "$scratch8/stderr.txt"; then
  common_test_pass "retained target: an existing file is refused with exit 2 and nothing is written"
else
  common_test_fail "retained target: expected exit 2 and no write (rc=$rc8; $(cat "$scratch8/stderr.txt"))"
fi

# ─── Case 9: a real write needs a session id ──────────────────────────────────────────────────
scratch9="$(build_scratch)"
write_state_fixture "$scratch9"
write_roadmap_fixture "$scratch9"
run_migrate "$scratch9" >/dev/null 2>"$scratch9/stderr.txt"
rc9=$?
if [[ "$rc9" -eq 1 ]] && grep -qF -- '--session-id is required' "$scratch9/stderr.txt"; then
  common_test_pass "usage: a real run without --session-id exits 1"
else
  common_test_fail "usage: expected exit 1 without --session-id (rc=$rc9)"
fi

# ─── Case 10: no roadmap file at all -- a state-only migration ────────────────────────────────
scratch10="$(build_scratch)"
write_state_fixture "$scratch10"
run_migrate "$scratch10" --session-id sess_test_10 >/dev/null 2>"$scratch10/stderr.txt"
rc10=$?
if [[ "$rc10" -eq 0 ]] \
    && jq -e '(.roadmap_milestones[0].batches | length) == 2 and (has("roadmap_notes") | not)' "$scratch10/specs/state.json" >/dev/null 2>&1 \
    && grep -qxF 'Notes postamble paragraph.' "$scratch10/specs/archive/retained.md" \
    && [[ "$(sed -n '1p' "$scratch10/specs/ROADMAP.md")" == "$SENTINEL" ]]; then
  common_test_pass "absent file: batches nest, notes are retained, and a generated file is written"
else
  common_test_fail "absent file: unexpected result (rc=$rc10; $(cat "$scratch10/stderr.txt"))"
fi

echo
echo "Results: $PASSED passed, $FAILED failed"
if [[ "$FAILED" -eq 0 ]]; then
  exit 0
else
  exit 1
fi
