#!/usr/bin/env bash
# test-approve-classify.sh - Regression suite for approve-classify.sh: one fixture per
# diff_since evidence kind, the declaration delta reported by name for added/removed/restated
# claims, the mechanical class reached only under the narrow bar, MEASURED vs INFERENCE per
# confidence-vocabulary.md, and a loud non-zero exit on a malformed review shape.
#
# Structural model: test-askuserquestion-rehome.sh (SCRIPT_DIR/git-worktree-first REPO_ROOT
# resolution, pass()/fail()/info() helpers, PASSED/FAILED counters, exit 0/1/2).
#
# Exit codes: 0 -- all cases PASS; 1 -- at least one case FAILED; 2 -- environment error.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR" && git rev-parse --show-toplevel 2>/dev/null)"
if [[ -z "$REPO_ROOT" ]]; then
  REPO_ROOT="$(cd "$SCRIPT_DIR/../../../.." && pwd)"
fi

PASSED=0
FAILED=0
pass() { echo "[PASS] $1"; PASSED=$((PASSED + 1)); }
fail() { echo "[FAIL] $1"; FAILED=$((FAILED + 1)); }
info() { echo "[INFO] $1"; }

SOURCE_STORE_SCRIPT="$REPO_ROOT/agent-system/extensions/approvals/scripts/approve-classify.sh"
DEPLOYED_SCRIPT="$REPO_ROOT/.claude/scripts/approve-classify.sh"
if [[ -f "$SOURCE_STORE_SCRIPT" ]]; then
  APPROVE_CLASSIFY="$SOURCE_STORE_SCRIPT"
elif [[ -f "$DEPLOYED_SCRIPT" ]]; then
  APPROVE_CLASSIFY="$DEPLOYED_SCRIPT"
else
  echo "ERROR: approve-classify.sh not found at either:" >&2
  echo "  $SOURCE_STORE_SCRIPT" >&2
  echo "  $DEPLOYED_SCRIPT" >&2
  exit 2
fi

if ! command -v jq >/dev/null 2>&1; then
  echo "ERROR: jq is required and was not found on PATH." >&2
  exit 2
fi

WORKDIR="$(mktemp -d)"
trap 'rm -rf "$WORKDIR"' EXIT

write_fixture() {
  local path="$1"
  shift
  printf '%s\n' "$@" > "$path"
}

# --- Fixture 1: identical evidence kind --------------------------------------------------
write_fixture "$WORKDIR/identical.md" \
  '# Approval review' \
  '' \
  'Generated by `approve.sh --review` on 2026-10-09 for the tree at deadbee.' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  '(no diff is available since commit deadbeef, which recorded the last approval: the change is' \
  'part of that commit'"'"'s history; review the full text)' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/identical.md")"
if echo "$out" | jq empty 2>/dev/null; then
  pass "identical fixture: output parses under jq empty"
else
  fail "identical fixture: output did not parse as JSON: $out"
fi
class="$(jq -r '.items[0].class' <<< "$out")"
confidence="$(jq -r '.items[0].confidence' <<< "$out")"
head="$(jq -r '.component_head' <<< "$out")"
if [[ "$class" == "mechanical" && "$confidence" == "MEASURED" ]]; then
  pass "identical fixture classifies mechanical/MEASURED"
else
  fail "identical fixture: expected mechanical/MEASURED, got $class/$confidence"
fi
if [[ "$head" == "deadbee" ]]; then
  pass "identical fixture: component_head captured verbatim from the review header"
else
  fail "identical fixture: expected component_head 'deadbee', got '$head'"
fi

# --- Fixture 2: diff adding a declaration -------------------------------------------------
write_fixture "$WORKDIR/decl-added.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  'Changes since commit oldsha, which recorded the last approval:' \
  '' \
  '```diff' \
  '+theorem Foo.NewClaim : True := trivial' \
  ' def unrelated := 1' \
  '```' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/decl-added.md")"
class="$(jq -r '.items[0].class' <<< "$out")"
added="$(jq -r '.items[0].decl_added[0]' <<< "$out")"
if [[ "$class" == "declaration-level" && "$added" == "Foo.NewClaim" ]]; then
  pass "decl-added fixture: reports Foo.NewClaim in decl_added, classifies declaration-level"
else
  fail "decl-added fixture: expected declaration-level/Foo.NewClaim, got $class/$added"
fi

# --- Fixture 3: diff removing a declaration (decl_removed by name) -----------------------
write_fixture "$WORKDIR/decl-removed.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  'Changes since commit oldsha, which recorded the last approval:' \
  '' \
  '```diff' \
  '-theorem Foo.OldClaim : True := trivial' \
  ' def unrelated := 1' \
  '```' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/decl-removed.md")"
removed="$(jq -r '.items[0].decl_removed[0]' <<< "$out")"
class="$(jq -r '.items[0].class' <<< "$out")"
if [[ "$removed" == "Foo.OldClaim" && "$class" == "declaration-level" ]]; then
  pass "decl-removed fixture: reports Foo.OldClaim in decl_removed, classifies declaration-level"
else
  fail "decl-removed fixture: expected declaration-level/Foo.OldClaim, got $class/$removed"
fi

# --- Fixture 4: diff restating a declaration (same name both sides) ----------------------
write_fixture "$WORKDIR/decl-restated.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  'Changes since commit oldsha, which recorded the last approval:' \
  '' \
  '```diff' \
  '-theorem Foo.Claim : True := trivial' \
  '+theorem Foo.Claim : 1 = 1 := rfl' \
  '```' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/decl-restated.md")"
restated="$(jq -r '.items[0].decl_restated[0]' <<< "$out")"
class="$(jq -r '.items[0].class' <<< "$out")"
if [[ "$restated" == "Foo.Claim" && "$class" == "declaration-level" ]]; then
  pass "decl-restated fixture: reports Foo.Claim in decl_restated, classifies declaration-level"
else
  fail "decl-restated fixture: expected declaration-level/Foo.Claim, got $class/$restated"
fi

# --- Fixture 5: comment-only diff (mechanical/INFERENCE) ---------------------------------
write_fixture "$WORKDIR/comment-only.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  'Changes since commit oldsha, which recorded the last approval:' \
  '' \
  '```diff' \
  '@@ -1,3 +1,3 @@' \
  '+-- a new comment line' \
  ' def unrelated := 1' \
  '---  an old comment line removed' \
  '```' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/comment-only.md")"
class="$(jq -r '.items[0].class' <<< "$out")"
confidence="$(jq -r '.items[0].confidence' <<< "$out")"
if [[ "$class" == "mechanical" && "$confidence" == "INFERENCE" ]]; then
  pass "comment-only fixture classifies mechanical/INFERENCE"
else
  fail "comment-only fixture: expected mechanical/INFERENCE, got $class/$confidence"
fi

# --- Fixture 6: never-approved evidence kind ----------------------------------------------
write_fixture "$WORKDIR/never-approved.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  '(never approved: review the full text)' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/never-approved.md")"
class="$(jq -r '.items[0].class' <<< "$out")"
evidence="$(jq -r '.items[0].evidence_kind' <<< "$out")"
if [[ "$class" == "needs-full-text" && "$evidence" == "never-approved" ]]; then
  pass "never-approved fixture classifies needs-full-text"
else
  fail "never-approved fixture: expected needs-full-text/never-approved, got $class/$evidence"
fi

# --- Fixture 7: uncommitted-approval evidence kind ----------------------------------------
write_fixture "$WORKDIR/uncommitted.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'no  spec  Foo.Bar  spec_digest=abc123' \
  '```' \
  '' \
  '## Evidence: Foo.Bar' \
  '' \
  '- file: `components/x/Foo.lean`' \
  '' \
  '(the last approval is not committed; no diff is available: review the full text)' \
  '' \
  '```lean' \
  'theorem Foo.Bar : True := trivial' \
  '```'

out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/uncommitted.md")"
class="$(jq -r '.items[0].class' <<< "$out")"
evidence="$(jq -r '.items[0].evidence_kind' <<< "$out")"
if [[ "$class" == "needs-full-text" && "$evidence" == "uncommitted-approval" ]]; then
  pass "uncommitted-approval fixture classifies needs-full-text"
else
  fail "uncommitted-approval fixture: expected needs-full-text/uncommitted-approval, got $class/$evidence"
fi

# --- Fixture 8: malformed ## Decisions block exits non-zero, heading named ---------------
write_fixture "$WORKDIR/malformed.md" \
  '# Approval review' \
  '' \
  '## Notes' \
  '' \
  '(The reviewer'"'"'s findings)' \
  '' \
  '## Decisions' \
  '' \
  '```' \
  'this is not a recognized decisions line' \
  '```'

if err_out="$(bash "$APPROVE_CLASSIFY" "$WORKDIR/malformed.md" 2>&1)"; then
  fail "malformed review: expected non-zero exit, got 0 ($err_out)"
else
  if grep -q "## Decisions" <<< "$err_out"; then
    pass "malformed ## Decisions block exits non-zero with the heading named"
  else
    fail "malformed review: refused, but did not name the offending heading: $err_out"
  fi
fi

echo
echo "=== test-approve-classify.sh: $PASSED passed, $FAILED failed ==="
[[ "$FAILED" -eq 0 ]]
